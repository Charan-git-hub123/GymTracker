-- GymTracker schema.[cite: 42]
--[cite: 42]
-- The repo previously had no schema, so a fresh clone could not create its own[cite: 42]
-- database. Run this once against DATABASE_URL:[cite: 42]
--   psql "$DATABASE_URL" -f schema.sql[cite: 42]

CREATE TABLE IF NOT EXISTS muscle_groups ([cite: 42]
    id   SERIAL PRIMARY KEY,[cite: 42]
    name TEXT NOT NULL UNIQUE[cite: 42]
);[cite: 42]

CREATE TABLE IF NOT EXISTS exercises ([cite: 42]
    id              SERIAL PRIMARY KEY,[cite: 42]
    muscle_group_id INTEGER NOT NULL REFERENCES muscle_groups(id) ON DELETE CASCADE,[cite: 42]
    name            TEXT NOT NULL,[cite: 42]
    description     TEXT,[cite: 42]
    youtube_link    TEXT,[cite: 42]
    UNIQUE (muscle_group_id, name)[cite: 42]
);[cite: 42]

CREATE TABLE IF NOT EXISTS exercise_logs ([cite: 42]
    id            SERIAL PRIMARY KEY,[cite: 42]
    exercise_id   INTEGER NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,[cite: 42]
    workout_date  DATE NOT NULL DEFAULT CURRENT_DATE[cite: 42]
);[cite: 42]

-- weight is NUMERIC, not INTEGER: 2.5 kg plates and 7.5 kg dumbbells exist, and[cite: 42]
-- the previous code scanned this column into an int.[cite: 42]
CREATE TABLE IF NOT EXISTS sets ([cite: 42]
    id              SERIAL PRIMARY KEY,[cite: 42]
    exercise_log_id INTEGER NOT NULL REFERENCES exercise_logs(id) ON DELETE CASCADE,[cite: 42]
    set_number      INTEGER NOT NULL,[cite: 42]
    weight          NUMERIC(6,2) NOT NULL DEFAULT 0,[cite: 42]
    reps            INTEGER NOT NULL DEFAULT 0[cite: 42]
);[cite: 42]

CREATE INDEX IF NOT EXISTS idx_exercises_muscle ON exercises(muscle_group_id);[cite: 42]
CREATE INDEX IF NOT EXISTS idx_logs_exercise    ON exercise_logs(exercise_id, workout_date DESC);[cite: 42]
CREATE INDEX IF NOT EXISTS idx_sets_log         ON sets(exercise_log_id, set_number);[cite: 42]

-- ON DELETE CASCADE above is what makes deleting a workout also remove its sets.[cite: 42]
-- Without it, deleting from exercise_logs left orphaned rows in sets.[cite: 42]

